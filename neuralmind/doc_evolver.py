class JSDocGenerator:
    """Generates JSDoc variants using mutation strategies.

    Each call to :meth:`generate` produces a variant by applying one or
    more mutation strategies to a base JSDoc template.
    """

    def __init__(self, rng: random.Random | None = None) -> None:
        self._rng = rng or random.Random()

    def generate(
        self,
        name: str,
        params: list[str] | None = None,
        method_type: str = "function",
        strategy: MutationStrategy | None = None,
    ) -> JSDocVariant:
        """Generate a JSDoc variant.

        Args:
            name: Method name.
            params: Parameter names.
            method_type: ``"function"``, ``"arrow"``, or ``"method"``.
            strategy: Specific strategy to use, or ``None`` for random.

        Returns:
            A ``JSDocVariant`` instance.
        """
        if strategy is None:
            strategy = self._sample_strategy()

        # Determine length
        length_class = self._rng.choice(list(LENGTH_VARIANTS.keys()))
        n_lines = LENGTH_VARIANTS[length_class]

        # Determine structure
        structure = self._rng.choice(STRUCTURE_VARIANTS)

        # Determine keyword density
        keyword_density = self._rng.choice(["synonyms", "generic"])

        # Determine position
        position = "above"  # default
        if method_type == "arrow":
            position = self._rng.choice(["above", "inline"])

        # Generate lines based on structure and length
        lines = self._build_lines(name, params or [], n_lines, structure, keyword_density)

        return JSDocVariant(
            strategy=strategy,
            lines=lines,
            length_class=length_class,
            structure=structure,
            keyword_density=keyword_density,
            position=position,
        )

    def _sample_strategy(self) -> MutationStrategy:
        """Sample a mutation strategy based on weights."""
        strategies = list(MutationStrategy)
        weights = [MUTATION_WEIGHTS[s.value] for s in strategies]
        return self._rng.choices(strategies, weights=weights, k=1)[0]

    def _build_lines(
        self,
        name: str,
        params: list[str],
        n_lines: int,
        structure: str,
        keyword_density: str,
    ) -> list[str]:
        """Build JSDoc lines based on structure and length constraints.

        Args:
            name: Method name.
            params: Parameter names.
            n_lines: Target number of lines.
            structure: ``"args_returns"``, ``"prose_only"``, or ``"mixed"``.
            keyword_density: ``"synonyms"`` or ``"generic"``.

        Returns:
            List of JSDoc content lines.
        """
        words = _camel_to_words(name)
        synonyms = _get_synonyms(name) if keyword_density == "synonyms" else []

        lines: list[str] = []

        if structure == "prose_only":
            # Prose-only: just a description
            desc = self._build_description(words, synonyms, keyword_density)
            lines.extend(self._wrap_text(desc, n_lines))

        elif structure == "args_returns":
            # Args/Returns/Raises structure
            desc = self._build_description(words, synonyms, keyword_density)
            lines.append(desc)

            if params and n_lines >= 3:
                for param in params[: n_lines - 2]:
                    lines.append(f"@param {{{param}}} — {param} parameter")

            if n_lines >= 2:
                lines.append("@returns {void}")

        else:  # mixed
            desc = self._build_description(words, synonyms, keyword_density)
            lines.append(desc)

            if params and n_lines >= 3:
                for param in params[: min(len(params), n_lines - 2)]:
                    lines.append(f"@param {{{param}}} — {param}")

            if n_lines >= 4 and params:
                lines.append("@returns {void}")

        # Truncate or pad to target length
        if len(lines) > n_lines:
            lines = lines[:n_lines]
        while len(lines) < n_lines:
            lines.append("")

        return lines

    def _build_description(self, words: str, synonyms: list[str], keyword_density: str) -> str:
        """Build a one-line description for the method.

        Args:
            words: Humanized method name.
            synonyms: List of synonym terms.
            keyword_density: ``"synonyms"`` or ``"generic"``.

        Returns:
            Description string.
        """
        if keyword_density == "synonyms" and synonyms:
            synonym = self._rng.choice(synonyms)
            templates = [
                f"{synonym.capitalize()} the {words}.",
                f"{synonym.capitalize()}s the {words}.",
                f"Used to {synonym} the {words}.",
            ]
        else:
            templates = [
                f"{words.capitalize()}.",
                f"Handles {words}.",
                f"Performs {words} operation.",
            ]
        return self._rng.choice(templates)

    def _wrap_text(self, text: str, n_lines: int) -> list[str]:
        """Wrap text into at most n_lines lines.

        Args:
            text: The text to wrap.
            n_lines: Maximum number of lines.

        Returns:
            List of wrapped lines.
        """
        if n_lines <= 1:
            return [text] if text else [""]

        words = text.split()
        if not words:
            return [""] * n_lines

        lines = []
        current = ""
        for word in words:
            if not current:
                current = word
            elif len(current) + 1 + len(word) <= 50:
                current += " " + word
            else:
                lines.append(current)
                current = word
        if current:
            lines.append(current)

        if len(lines) > n_lines:
            lines = lines[:n_lines]
        while len(lines) < n_lines:
            lines.append("")

        return lines

    def mutate_around(
        self,
        variant: JSDocVariant,
        name: str,
        params: list[str] | None = None,
        method_type: str = "function",
    ) -> JSDocVariant:
        """Create a new variant by mutating around an existing one.

        Preserves some attributes of the parent while randomly changing
        others — analogous to Gaussian perturbation in the tuner.

        Args:
            variant: The parent variant to mutate.
            name: Method name.
            params: Parameter names.
            method_type: ``"function"``, ``"arrow"``, or ``"method"``.

        Returns:
            A new ``JSDocVariant``.
        """
        # 50% chance to keep each attribute
        length_class = (
            variant.length_class
            if self._rng.random() < 0.5
            else self._rng.choice(list(LENGTH_VARIANTS.keys()))
        )
        structure = (
            variant.structure if self._rng.random() < 0.5 else self._rng.choice(STRUCTURE_VARIANTS)
        )
        keyword_density = (
            variant.keyword_density
            if self._rng.random() < 0.5
            else self._rng.choice(["synonyms", "generic"])
        )
        position = variant.position
        if method_type == "arrow" and self._rng.random() < 0.3:
            position = "inline" if position == "above" else "above"

        n_lines = LENGTH_VARIANTS[length_class]
        lines = self._build_lines(name, params or [], n_lines, structure, keyword_density)

        return JSDocVariant(
            strategy=self._sample_strategy(),
            lines=lines,
            length_class=length_class,
            structure=structure,
            keyword_density=keyword_density,
            position=position,
        )


