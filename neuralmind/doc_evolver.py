def audit_blind_spots(project_path: str | Path) -> list[BlindSpot]:
    """Scan a project for undocumented public methods.

    Walks the source tree, parses JS/TS files, and identifies public
    methods/functions lacking JSDoc comments. This is a lightweight
    heuristic audit — for a full AST audit, use a proper parser.

    Args:
        project_path: Path to the project root.

    Returns:
        List of ``BlindSpot`` instances for undocumented methods.
    """
    project_path = Path(project_path)
    spots: list[BlindSpot] = []

    skip_dirs = {
        "node_modules",
        ".git",
        "dist",
        "build",
        ".next",
        "coverage",
        "__pycache__",
        ".venv",
        "venv",
        ".neuralmind",
        "graphify-out",
    }

    source_extensions = {".js", ".ts", ".jsx", ".tsx", ".mjs", ".cjs"}

    for root, dirs, files in __import__("os").walk(project_path):
        dirs[:] = [d for d in dirs if d not in skip_dirs]
        for fname in files:
            if not any(fname.endswith(ext) for ext in source_extensions):
                continue
            file_path = __import__("pathlib").Path(root) / fname
            rel_path = file_path.relative_to(project_path)
            try:
                content = file_path.read_text(encoding="utf-8", errors="ignore")
                spots.extend(_scan_file_for_blind_spots(content, str(rel_path)))
            except Exception:
                continue

    return spots


def _scan_file_for_blind_spots(content: str, file_path: str) -> list[BlindSpot]:
    """Scan a single file for undocumented methods.

    Args:
        content: File content.
        file_path: Relative file path.

    Returns:
        List of ``BlindSpot`` instances.
    """
    spots: list[BlindSpot] = []
    lines = content.splitlines()

    # Patterns for method/function declarations
    patterns = [
        # function name(...) or export function name(...)
        re.compile(r"^\s*(?:export\s+)?(?:async\s+)?function\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*\("),
        # const name = (...) => or const name = function(...)
        re.compile(
            r"^\s*(?:export\s+)?(?:const|let|var)\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*(?:async\s+)?(?:\(|function\b)"
        ),
        # class method: name(...) {
        re.compile(r"^\s*(?:async\s+)?([a-zA-Z_][a-zA-Z0-9_]*)\s*\([^)]*\)\s*\{"),
    ]

    for i, line in enumerate(lines):
        for pattern in patterns:
            match = pattern.match(line)
            if not match:
                continue

            name = match.group(1)

            # Skip common non-method patterns
            if name in ("if", "while", "for", "switch", "catch", "return"):
                continue

            # Check if preceded by JSDoc
            has_jsdoc = False
            for j in range(i - 1, max(i - 10, -1), -1):
                if j < 0:
                    break
                stripped = lines[j].strip()
                if stripped.endswith("*/"):
                    has_jsdoc = True
                    break
                if stripped and not stripped.startswith("//"):
                    break

            if has_jsdoc:
                continue

            # Detect method type and params
            method_type = _detect_method_type(line)
            params = _extract_params(line)

            spots.append(
                BlindSpot(
                    name=name,
                    file_path=file_path,
                    line=i + 1,  # 1-based
                    method_type=method_type,
                    params=params,
                )
            )
            break  # Only match first pattern per line

    return spots
