log = logging.getLogger(__name__)


# ----------------------------------------------------------------------- #
# Constants
# ----------------------------------------------------------------------- #

MAX_GENERATIONS = 5
POPULATION_SIZE = 5
HYSTERESIS = 0.05

# Mutation strategy weights for sampling
MUTATION_WEIGHTS = {
    "LENGTH": 0.3,
    "STRUCTURE": 0.3,
    "KEYWORD_DENSITY": 0.25,
    "POSITION": 0.15,
}

# JSDoc length variants
LENGTH_VARIANTS = {
    "short": 1,  # 1-line
    "medium": 3,  # 3-line
    "long": 5,  # 5-line
}

# JSDoc structure variants
STRUCTURE_VARIANTS = [
    "args_returns",  # Args/Returns/Raises
    "prose_only",  # prose-only
    "mixed",  # mixed
]


# ----------------------------------------------------------------------- #
# Dataclasses
# ----------------------------------------------------------------------- #


class MutationStrategy(Enum):
    """Mutation strategies for JSDoc variant generation."""

    LENGTH = "LENGTH"
    STRUCTURE = "STRUCTURE"
    KEYWORD_DENSITY = "KEYWORD_DENSITY"
    POSITION = "POSITION"


@dataclass
class BlindSpot:
    """A method lacking documentation — the target for JSDoc evolution.

    Args:
        name: Method name (e.g. ``"handleCSVExport"``).
        file_path: Path to the source file (relative to project root).
        line: 1-based line number where the method is defined.
        method_type: Kind of method — ``"function"``, ``"arrow"``, ``"method"``.
        params: List of parameter names, if known.
    """

    name: str
    file_path: str
    line: int
    method_type: str = "function"
    params: list[str] = field(default_factory=list)


@dataclass
class JSDocVariant:
    """A single JSDoc candidate generated by mutation.

    Args:
        strategy: The mutation strategy that produced this variant.
        lines: The JSDoc lines (without ``/**`` / ``*/`` delimiters).
        length_class: ``"short"``, ``"medium"``, or ``"long"``.
        structure: ``"args_returns"``, ``"prose_only"``, or ``"mixed"``.
        keyword_density: ``"synonyms"`` or ``"generic"``.
        position: ``"above"`` or ``"inline"``.
    """

    strategy: MutationStrategy
    lines: list[str]
    length_class: str = "medium"
    structure: str = "args_returns"
    keyword_density: str = "synonyms"
    position: str = "above"

    @property
    def text(self) -> str:
        """Render the variant as a complete JSDoc comment block."""
        if not self.lines:
            return ""
        body = "\n".join(f" * {line}" if line.strip() else " *" for line in self.lines)
        return f"/**\n{body}\n */"


@dataclass
class EvolveResult:
    """Result of evolving a single blind spot.

    Args:
        name: Method name.
        file_path: Source file path.
        line: Line number.
        best_fitness: Best Recall@1 achieved across all generations.
        best_variant: The winning JSDoc variant.
        generations_run: Number of generations actually executed.
        promoted: Whether any variant improved over the baseline.
    """

    name: str
    file_path: str
    line: int
    best_fitness: float
    best_variant: JSDocVariant | None
    generations_run: int
    promoted: bool


@dataclass
class GenerationResult:
    """Result of a single evolution generation.

    Args:
        generation: Generation index (0-based).
        population_size: Number of candidates evaluated.
        best_fitness: Best fitness in this generation.
        incumbent_fitness: Fitness of the incumbent (best so far).
        promoted: Whether the best candidate was promoted.
        best_variant: The best variant in this generation.
    """

    generation: int
    population_size: int
    best_fitness: float
    incumbent_fitness: float
    promoted: bool
    best_variant: JSDocVariant | None


