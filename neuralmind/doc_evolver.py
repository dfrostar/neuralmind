class DocEvolver:
    """Evolutionary optimizer that generates and selects JSDoc for undocumented methods.

    For each blind spot (undocumented method), the evolver:
    1. Generates N JSDoc variants using mutation strategies.
    2. Patches each variant into the code, builds the index, runs a retrieval query.
    3. Scores each variant by Recall@1 (1/rank of correct file).
    4. Promotes the winning variant, mutates around it, repeats for G generations.
    5. After evolution, patches the winning JSDoc into the actual source files.

    Configurable via env:
      - NEURALMIND_DOC_EVOLVER_POPULATION (default 5)
      - NEURALMIND_DOC_EVOLVER_GENERATIONS (default 5)
      - NEURALMIND_DOC_EVOLVER_HYSTERESIS (default 0.05)

    Args:
        project_path: Path to the project root.
        blind_spots: List of undocumented methods to evolve JSDoc for.
        population_size: Candidates per generation (default 5).
        generations: Max generations per blind spot (default 5).
        hysteresis: Promotion margin (default 0.05).
        query_fn: Optional callable ``(project_path, query) -> list[str]`` that
            returns ranked source files for a query. Defaults to running
            ``neuralmind query`` via subprocess. Injected for testability.

    Raises:
        ValueError: If ``blind_spots`` is empty.
    """

    def __init__(
        self,
        project_path: str | Path,
        blind_spots: list[BlindSpot],
        population_size: int | None = None,
        generations: int | None = None,
        hysteresis: float | None = None,
        query_fn: Any = None,
    ) -> None:
        if not blind_spots:
            raise ValueError("blind_spots must not be empty")

        self.project_path = Path(project_path).resolve()
        self.blind_spots = blind_spots
        self.population_size = population_size or int(
            __import__("os").environ.get("NEURALMIND_DOC_EVOLVER_POPULATION", POPULATION_SIZE)
        )
        self.generations = generations or int(
            __import__("os").environ.get("NEURALMIND_DOC_EVOLVER_GENERATIONS", MAX_GENERATIONS)
        )
        self.hysteresis = hysteresis or float(
            __import__("os").environ.get("NEURALMIND_DOC_EVOLVER_HYSTERESIS", HYSTERESIS)
        )
        self.query_fn = query_fn
        self._rng = random.Random()
        self._generator = JSDocGenerator(self._rng)

        # Defensive coerce
        if self.hysteresis <= 0.0:
            log.warning("hysteresis must be positive, got %r — using default 0.05", self.hysteresis)
            self.hysteresis = 0.05
        if self.population_size <= 0:
            log.warning(
                "population_size must be positive, got %r — using default 5", self.population_size
            )
            self.population_size = POPULATION_SIZE
        if self.generations <= 0:
            log.warning("generations must be positive, got %r — using default 5", self.generations)
            self.generations = MAX_GENERATIONS

    # ------------------------------------------------------------------- #
    # Public API
    # ------------------------------------------------------------------- #

    def evolve(self) -> list[EvolveResult]:
        """Run evolution for all blind spots.

        Returns:
            List of ``EvolveResult``, one per blind spot. Fail-open:
            if evolution fails for a spot, the result has ``best_fitness=0.0``
            and ``best_variant=None``.
        """
        results: list[EvolveResult] = []
        for spot in self.blind_spots:
            try:
                result = self._evolve_one(spot)
                results.append(result)
            except Exception as exc:
                log.warning("evolution failed for %s:%s: %s", spot.file_path, spot.name, exc)
                results.append(
                    EvolveResult(
                        name=spot.name,
                        file_path=spot.file_path,
                        line=spot.line,
                        best_fitness=0.0,
                        best_variant=None,
                        generations_run=0,
                        promoted=False,
                    )
                )
        return results

    def patch_winners(self, results: list[EvolveResult]) -> list[str]:
        """Patch winning JSDoc variants into source files.

        Args:
            results: Results from :meth:`evolve`.

        Returns:
            List of file paths that were modified.
        """
        modified: list[str] = []
        for result in results:
            if result.best_variant is None:
                continue
            file_path = self.project_path / result.file_path
            if not file_path.exists():
                log.warning("source file not found: %s", file_path)
                continue
            try:
                self._patch_file(file_path, result.line, result.best_variant)
                modified.append(result.file_path)
            except Exception as exc:
                log.warning("failed to patch %s: %s", file_path, exc)
        return modified

    # ------------------------------------------------------------------- #
    # Evolution loop
    # ------------------------------------------------------------------- #

    def _evolve_one(self, spot: BlindSpot) -> EvolveResult:
        """Evolve JSDoc for a single blind spot.

        Args:
            spot: The blind spot to evolve.

        Returns:
            ``EvolveResult`` with the best variant found. If all
            evaluations fail, returns ``best_variant=None``.
        """
        # Detect method type and params from source if not provided
        source_params = spot.params
        source_method_type = spot.method_type
        if not source_params or source_method_type == "function":
            detected = self._inspect_source(spot)
            if detected:
                source_method_type = detected[0]
                if not source_params:
                    source_params = detected[1]

        # Generate initial population
        incumbent_variant = self._generator.generate(spot.name, source_params, source_method_type)
        incumbent_fitness = self._evaluate_candidate(spot, incumbent_variant)

        best_variant = incumbent_variant if incumbent_fitness > 0 else None
        best_fitness = incumbent_fitness
        promoted = False

        for _gen in range(self.generations):
            gen_best_variant = incumbent_variant
            gen_best_fitness = incumbent_fitness

            for _ in range(self.population_size):
                candidate = self._generator.mutate_around(
                    incumbent_variant, spot.name, source_params, source_method_type
                )
                candidate_fitness = self._evaluate_candidate(spot, candidate)
                if candidate_fitness > gen_best_fitness:
                    gen_best_fitness = candidate_fitness
                    gen_best_variant = candidate

            if self.promote_if_better(gen_best_fitness, incumbent_fitness):
                incumbent_variant = gen_best_variant
                incumbent_fitness = gen_best_fitness
                best_variant = gen_best_variant
                best_fitness = gen_best_fitness
                promoted = True
            else:
                if gen_best_fitness > best_fitness:
                    best_variant = gen_best_variant
                    best_fitness = gen_best_fitness

        return EvolveResult(
            name=spot.name,
            file_path=spot.file_path,
            line=spot.line,
            best_fitness=best_fitness,
            best_variant=best_variant,
            generations_run=self.generations,
            promoted=promoted,
        )

    def run_generation(
        self,
        spot: BlindSpot,
        incumbent_variant: JSDocVariant,
        incumbent_fitness: float,
        source_params: list[str],
        source_method_type: str,
    ) -> GenerationResult:
        """Run one generation of evolution for a blind spot.

        Exposed for testing and external orchestration. Each generation
        samples ``population_size`` candidates, evaluates them, and
        promotes the best if it beats the incumbent by the hysteresis
        margin.

        Args:
            spot: The blind spot.
            incumbent_variant: Current best variant.
            incumbent_fitness: Fitness of the incumbent.
            source_params: Parameter names.
            source_method_type: Method type.

        Returns:
            ``GenerationResult`` for this generation.
        """
        gen_best_variant = incumbent_variant
        gen_best_fitness = incumbent_fitness

        for _ in range(self.population_size):
            candidate = self._generator.mutate_around(
                incumbent_variant, spot.name, source_params, source_method_type
            )
            candidate_fitness = self._evaluate_candidate(spot, candidate)
            if candidate_fitness > gen_best_fitness:
                gen_best_fitness = candidate_fitness
                gen_best_variant = candidate

        promoted = self.promote_if_better(gen_best_fitness, incumbent_fitness)
        if promoted:
            incumbent_variant = gen_best_variant
            incumbent_fitness = gen_best_fitness

        return GenerationResult(
            generation=0,
            population_size=self.population_size,
            best_fitness=gen_best_fitness,
            incumbent_fitness=incumbent_fitness,
            promoted=promoted,
            best_variant=gen_best_variant,
        )

    def sample_candidate(
        self,
        incumbent: JSDocVariant,
        name: str,
        params: list[str],
        method_type: str,
    ) -> JSDocVariant:
        """Sample a candidate variant by mutating around the incumbent.

        Args:
            incumbent: The current best variant.
            name: Method name.
            params: Parameter names.
            method_type: Method type.

        Returns:
            A new ``JSDocVariant``.
        """
        return self._generator.mutate_around(incumbent, name, params, method_type)

    def evaluate_candidate(
        self,
        spot: BlindSpot,
        variant: JSDocVariant,
    ) -> float:
        """Evaluate a JSDoc variant against the retrieval fitness function.

        Patches the variant into the source, runs a natural-language query,
        and scores by Recall@1 (1/rank of correct file).

        Args:
            spot: The blind spot.
            variant: The JSDoc variant to evaluate.

        Returns:
            Fitness score in [0, 1].
        """
        return self._evaluate_candidate(spot, variant)

    def promote_if_better(self, candidate_fitness: float, incumbent_fitness: float) -> bool:
        """Check if candidate should be promoted over incumbent.

        Args:
            candidate_fitness: Fitness of the candidate.
            incumbent_fitness: Fitness of the incumbent.

        Returns:
            ``True`` if candidate beats incumbent by hysteresis margin.
        """
        return candidate_fitness > incumbent_fitness * (1.0 + self.hysteresis)

    # ------------------------------------------------------------------- #
    # Internal evaluation
    # ------------------------------------------------------------------- #

    def _evaluate_candidate(self, spot: BlindSpot, variant: JSDocVariant) -> float:
        """Score a variant by patching, querying, and measuring Recall@1.

        Patches the JSDoc into the actual source file, rebuilds the index,
        runs a retrieval query, then restores the original content.

        Args:
            spot: The blind spot.
            variant: The JSDoc variant.

        Returns:
            Recall@1 score (1/rank, 0.0 if not found).
        """
        file_path = self.project_path / spot.file_path
        if not file_path.exists():
            log.warning("source file not found: %s", file_path)
            return 0.0

        # Read original source
        original_content = file_path.read_text(encoding="utf-8")
        lines = original_content.splitlines()

        # Find the actual line (handle offset from AST)
        insert_line = self._find_method_line(lines, spot)
        if insert_line is None:
            log.warning("could not locate method %s in %s", spot.name, spot.file_path)
            return 0.0

        # Patch in the JSDoc
        jsdoc_lines = variant.text.splitlines()
        patched_lines = lines[:insert_line] + jsdoc_lines + lines[insert_line:]
        patched_content = "\n".join(patched_lines) + "\n"

        # Write patched content to actual source file, rebuild index, query, restore
        # Use atomic file ops: backup first, restore via os.replace() to prevent
        # data corruption if the process is killed (SIGKILL, OOM) between write and finally.
        import shutil

        backup_path = file_path.with_suffix(file_path.suffix + ".bak")
        shutil.copy2(file_path, backup_path)
        try:
            file_path.write_text(patched_content, encoding="utf-8")

            # Rebuild index with patched content
            build_result = subprocess.run(
                [sys.executable, "-m", "neuralmind.cli", "build", str(self.project_path)],
                capture_output=True,
                text=True,
                timeout=120,
            )
            if build_result.returncode != 0:
                log.warning("neuralmind build failed: %s", build_result.stderr)
                return 0.0

            # Build query from method name
            query = _camel_to_words(spot.name)

            # Run query
            ranked_files = self._run_query(query)

            # Score by rank of correct file
            target_file = spot.file_path.replace("\\", "/")
            for rank, filepath in enumerate(ranked_files, start=1):
                if filepath.replace("\\", "/") == target_file:
                    return 1.0 / rank

            return 0.0

        except Exception as exc:
            log.warning("evaluation failed for %s: %s", spot.name, exc)
            return 0.0

        finally:
            # Always restore original content atomically from backup
            backup_path.replace(file_path)

    def _run_query(self, query: str) -> list[str]:
        """Run a retrieval query and return ranked source files.

        Uses the injected ``query_fn`` if provided (for testing), otherwise
        shells out to ``neuralmind query`` and parses the JSON output.

        Args:
            query: Natural-language query string.

        Returns:
            List of source file paths, ranked by relevance.
        """
        if self.query_fn is not None:
            return self.query_fn(str(self.project_path), query)

        # Shell out to neuralmind query
        try:
            result = subprocess.run(
                [sys.executable, "-m", "neuralmind.cli", "query", str(self.project_path), query, "--json"],
                capture_output=True,
                text=True,
                timeout=60,
            )
            if result.returncode != 0:
                log.warning("neuralmind query failed: %s", result.stderr)
                return []

            data = json.loads(result.stdout)
            context = data.get("context", "")

            # Parse file paths from markdown search results
            # Pattern: "File: path/to/file.ext" or "**file** (score: N)\n   Type: code\n   File: path"
            # Use permissive regex that captures paths with spaces by requiring
            # the path to end with a recognized code extension.
            code_exts = (
                ".ts",
                ".tsx",
                ".py",
                ".js",
                ".jsx",
                ".go",
                ".rs",
                ".java",
                ".cs",
                ".cpp",
                ".c",
                ".rb",
                ".php",
            )
            file_pattern = re.compile(
                r"File:\s+([^\s,\n]+?\.(?:" + "|".join(ext.lstrip(".") for ext in code_exts) + "))"
            )
            files = []
            for match in file_pattern.finditer(context):
                f = match.group(1).strip()
                # Filter: require BOTH path separator AND recognized code extension
                if "/" in f and f.endswith(code_exts):
                    files.append(f)
            return files

        except (subprocess.TimeoutExpired, json.JSONDecodeError, FileNotFoundError) as exc:
            log.warning("query execution failed: %s", exc)
            return []

    def _find_method_line(self, lines: list[str], spot: BlindSpot) -> int | None:
        """Find the line index where JSDoc should be inserted.

        Searches around the expected line number for the method signature.

        Args:
            lines: Source file lines.
            spot: The blind spot.

        Returns:
            0-based line index for insertion, or ``None`` if not found.
        """
        # Search within a window around the expected line
        window = 10
        start = max(0, spot.line - window - 1)
        end = min(len(lines), spot.line + window)

        # Pattern to match the method name
        name_pattern = re.compile(r"\b" + re.escape(spot.name) + r"\b")

        for i in range(start, end):
            if name_pattern.search(lines[i]):
                # Check if there's already a JSDoc comment above
                if i > 0 and lines[i - 1].strip().endswith("*/"):
                    return None  # Already documented
                return i

        # Fallback: try the exact line
        if 0 <= spot.line - 1 < len(lines):
            return spot.line - 1

        return None

    # ------------------------------------------------------------------- #
    # Source inspection
    # ------------------------------------------------------------------- #

    def _inspect_source(self, spot: BlindSpot) -> tuple[str, list[str]] | None:
        """Inspect source file to detect method type and parameters.

        Args:
            spot: The blind spot.

        Returns:
            Tuple of ``(method_type, params)`` or ``None`` if file not found.
        """
        file_path = self.project_path / spot.file_path
        if not file_path.exists():
            return None

        try:
            lines = file_path.read_text(encoding="utf-8").splitlines()
            for _i, line in enumerate(lines):
                if spot.name in line:
                    method_type = _detect_method_type(line)
                    params = _extract_params(line)
                    return method_type, params
        except Exception:
            pass

        return None

    # ------------------------------------------------------------------- #
    # Patching
    # ------------------------------------------------------------------- #

    def _patch_file(self, file_path: Path, line: int, variant: JSDocVariant) -> None:
        """Patch a JSDoc variant into a source file.

        Args:
            file_path: Path to the source file.
            line: 1-based line number of the method.
            variant: The JSDoc variant to insert.

        Raises:
            FileNotFoundError: If the file doesn't exist.
            ValueError: If the method can't be located.
        """
        content = file_path.read_text(encoding="utf-8")
        lines = content.splitlines()

        # Find the method by line number
        insert_idx = self._find_method_line_by_number(lines, line)
        if insert_idx is None:
            raise ValueError(f"could not locate method at line {line}")

        # Check if already documented
        if insert_idx > 0 and lines[insert_idx - 1].strip().endswith("*/"):
            return  # Already has JSDoc

        # Insert JSDoc
        jsdoc_lines = variant.text.splitlines()
        new_lines = lines[:insert_idx] + jsdoc_lines + lines[insert_idx:]
        new_content = "\n".join(new_lines) + "\n"

        file_path.write_text(new_content, encoding="utf-8")

    def _find_method_line_by_number(self, lines: list[str], line: int) -> int | None:
        """Find the 0-based line index for a 1-based line number.

        Args:
            lines: Source file lines.
            line: 1-based line number.

        Returns:
            0-based index, or ``None`` if out of range.
        """
        idx = line - 1
        if 0 <= idx < len(lines):
            return idx
        return None


