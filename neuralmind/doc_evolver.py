"""doc_evolver.py — evolutionary JSDoc optimizer for undocumented methods.

Finds blind spots (undocumented public methods) via AST audit, generates
JSDoc variants using mutation strategies (LENGTH, STRUCTURE, KEYWORD_DENSITY,
POSITION), and evolves them against a retrieval fitness function: each
variant is patched into the code, the index is rebuilt, and a natural-language
query is run to score Recall@1. The winning variant is promoted through
generations of mutation, then patched back into the source.

Example:
    >>> from neuralmind.doc_evolver import DocEvolver, BlindSpot
    >>> spots = [BlindSpot(name="handleCSVExport", file_path="src/export.ts", line=42)]
    >>> evolver = DocEvolver(project_path=".", blind_spots=spots)
    >>> results = evolver.evolve()
    >>> for r in results:
    ...     print(f"{r.name}: fitness={r.best_fitness:.3f}")

See Also:
    - ``neuralmind/tuner.py`` — population-based evolutionary search (C3)
    - ``neuralmind/probe.py`` — label-free retrieval self-probe
    - ``tests/test_doc_evolver.py`` — test cases and usage patterns
    - ``docs/wiki/Architecture.md#doc-evolver`` — high-level design

Version:
    0.53.0
"""

