def _camel_to_words(name: str) -> str:
    """Convert a camelCase/PascalCase identifier to space-separated words.

    Args:
        name: Identifier like ``"handleCSVExport"``.

    Returns:
        Lowercased words like ``"handle csv export"``.
    """
    # Step 1: Handle acronym followed by word (CSVExport -> CSV Export)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1 \2", name)
    # Step 2: Handle camelCase boundary (handleCSV -> handle CSV)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", s)
    # Step 3: Clean up and lowercase
    s = re.sub(r"\s+", " ", s).strip()
    return s.lower()


def _get_synonyms(name: str) -> list[str]:
    """Generate synonyms/related terms for a method name.

    Args:
        name: Method name.

    Returns:
        List of synonym strings.
    """
    words = _camel_to_words(name).split()
    synonyms: list[str] = []

    # Common verb synonyms (handles both base forms and acronyms)
    verb_map = {
        "get": ["fetch", "retrieve", "obtain", "read"],
        "set": ["update", "assign", "configure", "write"],
        "create": ["make", "build", "generate", "construct", "add"],
        "delete": ["remove", "destroy", "clear", "drop"],
        "update": ["modify", "edit", "change", "patch"],
        "handle": ["process", "manage", "deal with"],
        "export": ["output", "save", "write", "serialize"],
        "import": ["load", "read", "parse", "ingest"],
        "validate": ["check", "verify", "ensure"],
        "format": ["transform", "convert", "render"],
        "parse": ["decode", "interpret", "extract"],
        "init": ["initialize", "setup", "start"],
        "calc": ["compute", "calculate", "determine"],
        "send": ["dispatch", "transmit", "emit"],
        "recv": ["receive", "accept", "listen"],
        "csv": ["comma-separated", "tabular", "spreadsheet"],
        "json": ["object", "structured data"],
        "xml": ["markup", "hierarchical"],
        "html": ["rendered", "web"],
        "report": ["summary", "output", "document"],
        "data": ["information", "content", "records"],
        "file": ["document", "resource", "asset"],
    }

    for word in words:
        if word in verb_map:
            synonyms.extend(verb_map[word])

    return synonyms


def _detect_method_type(source_line: str) -> str:
    """Detect whether a source line is a function, arrow function, or method.

    Args:
        source_line: The source code line.

    Returns:
        ``"arrow"``, ``"method"``, or ``"function"``.
    """
    stripped = source_line.strip()
    if "=>" in stripped and ("const " in stripped or "let " in stripped or "var " in stripped):
        return "arrow"
    if re.search(r"^\s*(async\s+)?[a-zA-Z_][a-zA-Z0-9_]*\s*\(", stripped):
        if "function" not in stripped:
            return "method"
    return "function"


def _extract_params(source_line: str) -> list[str]:
    """Extract parameter names from a method signature.

    Args:
        source_line: The source code line containing the method signature.

    Returns:
        List of parameter names.
    """
    # Match content inside parentheses
    match = re.search(r"\(([^)]*)\)", source_line)
    if not match:
        return []

    params_str = match.group(1).strip()
    if not params_str:
        return []

    params = []
    for param in params_str.split(","):
        param = param.strip()
        if not param:
            continue
        # Handle default values
        param = param.split("=")[0].strip()
        # Handle destructuring
        if param.startswith(("{", "[")):
            continue
        # Handle type annotations (TypeScript)
        param = param.split(":")[0].strip()
        # Handle rest parameter
        if param.startswith("..."):
            param = param[3:]
        if param and re.match(r"^[a-zA-Z_][a-zA-Z0-9_]*$", param):
            params.append(param)

    return params


